static std::vector<std::uint8_t> bytes(const std::string& s) { return {s.begin(), s.end()}; }

static std::vector<std::uint8_t> dynamicText() {
    std::string s;
    char line[96];
    for (int i = 0; i < 200; ++i) {
        std::snprintf(line, sizeof line, "line %d: lorem ipsum dolor sit amet, POM68K zip gate\n", i);
        s += line;
    }
    return bytes(s);
}

int main() {
    const auto fox = bytes("The quick brown fox jumps over the lazy dog. The quick brown fox!");
    const auto text = dynamicText();
    std::string err;
    std::vector<std::uint8_t> out;

    // ── inflate ──────────────────────────────────────────────────────────
    check(zip::inflate(kFixed.data(), kFixed.size(), out, 1 << 20, err) && out == fox,
          "inflate: fixed-Huffman block");
    check(zip::inflate(kDynamic.data(), kDynamic.size(), out, 1 << 20, err) && out == text,
          "inflate: dynamic-Huffman block (" + std::to_string(text.size()) + " bytes)");
    check(crc32(text) == 0xB108D06Cu, "CRC-32 of the dynamic text is zlib's");
    check(zip::inflate(kStored.data(), kStored.size(), out, 1 << 20, err) && out == fox,
          "inflate: stored block");
    check(!zip::inflate(kDynamic.data(), kDynamic.size(), out, 1000, err) &&
              err.find("cap") != std::string::npos,
          "inflate: stops at the output cap (" + err + ")");
    check(!zip::inflate(kDynamic.data(), kDynamic.size() / 2, out, 1 << 20, err),
          "inflate: a truncated stream is an error");
    {
        const std::uint8_t reserved[] = {0x07};   // BFINAL=1, BTYPE=3
        check(!zip::inflate(reserved, 1, out, 64, err), "inflate: reserved block type refused");
    }
    check(crc32(fox) == 0x0E45B81Fu, "CRC-32 (IEEE) known value");
    {
        const auto v = bytes("123456789");
        check(crc32(v) == 0xCBF43926u, "CRC-32 check value of \"123456789\"");
    }

    // ── archives ─────────────────────────────────────────────────────────
    testzip::Member fixedM{"deflated/fixed.txt", kFixed, 8, std::uint32_t(fox.size()), crc32(fox)};
    testzip::Member dynM{"deflated/dynamic.txt", kDynamic, 8, std::uint32_t(text.size()), crc32(text)};
    const auto good = testzip::make({testzip::stored("dir/", {}), testzip::stored("a.bin", fox),
                                     fixedM, dynM});
    std::vector<zip::Entry> entries;
    check(zip::looksLikeZip(good), "looksLikeZip on a zip");
    check(zip::listEntries(good, entries, err) && entries.size() == 4,
          "listEntries: four entries");
    check(entries.size() == 4 && entries[0].directory() && !entries[1].directory(),
          "directory entries are flagged");
    check(zip::totalUncompressed(entries) == fox.size() * 2 + text.size(),
          "totalUncompressed sums the declared sizes");
    check(zip::readMember(good, "a.bin", out, err, 1 << 20) && out == fox, "stored member");
    check(zip::readMember(good, "deflated/fixed.txt", out, err, 1 << 20) && out == fox,
          "deflated member (fixed)");
    check(zip::readMember(good, "deflated/dynamic.txt", out, err, 1 << 20) && out == text,
          "deflated member (dynamic)");
    check(!zip::readMember(good, "absent", out, err, 1 << 20) &&
              err.find("not in the archive") != std::string::npos,
          "absent member named in the error");
    check(!zip::readMember(good, "deflated/dynamic.txt", out, err, 4096) &&
              err.find("cap") != std::string::npos,
          "a member declaring more than the cap is refused before inflating");

    // A member that claims 100 bytes but inflates to 10690: the inflater
    // stops at the declared size.
    {
        testzip::Member liar{"liar", kDynamic, 8, 100, crc32(text)};
        const auto z = testzip::make({liar});
        check(!zip::readMember(z, "liar", out, err, 1 << 20) && out.empty(),
              "a stream longer than its declared size is refused (" + err + ")");
    }
    {
        testzip::Member bad = testzip::stored("bad", fox);
        bad.crc = 0x12345678;
        const auto z = testzip::make({bad});
        check(!zip::readMember(z, "bad", out, err, 1 << 20) &&
                  err.find("CRC") != std::string::npos,
              "CRC-32 mismatch refused");
    }
    {
        testzip::Member enc = testzip::stored("enc", fox);
        auto z = testzip::make({enc});
        // Set bit 0 of the general-purpose flag in the central directory.
        std::vector<zip::Entry> es;
        zip::listEntries(z, es, err);
        const std::size_t cdOff = z.size() - 22 - (46 + 3);
        z[cdOff + 8] |= 1;
        check(!zip::readMember(z, "enc", out, err, 1 << 20) &&
                  err.find("encrypted") != std::string::npos,
              "encrypted member refused");
    }
    {
        testzip::Member b64{"bz", fox, 12, 0, 0};
        const auto z = testzip::make({b64});
        check(!zip::readMember(z, "bz", out, err, 1 << 20) &&
                  err.find("method 12") != std::string::npos,
              "unsupported method refused, by number");
    }
    {
        auto z = good;
        z.resize(z.size() - 1);
        check(!zip::looksLikeZip(z) && !zip::listEntries(z, entries, err),
              "a truncated archive has no end record");
    }
    {
        // The directory says the member is longer than the bytes that
        // follow its header.
        auto z = testzip::make({testzip::stored("big", text)});
        const std::size_t cd = z.size() - 22 - (46 + 3);
        for (std::size_t f : {std::size_t(20), std::size_t(24)}) {
            z[cd + f] = 0x50; z[cd + f + 1] = 0xC3; z[cd + f + 2] = 0; z[cd + f + 3] = 0;
        }
        check(zip::listEntries(z, entries, err) &&
                  !zip::readEntry(z, entries[0], out, err, 1 << 20) &&
                  err.find("truncated") != std::string::npos,
              "truncated member refused (" + err + ")");
    }
    {
        const auto html = bytes("<!DOCTYPE html><html><body>Item not available</body></html>");
        check(!zip::looksLikeZip(html) && !zip::listEntries(html, entries, err) &&
                  err.find("not a zip") != std::string::npos,
              "an HTML page is not a zip (" + err + ")");
    }
    {
        auto z = good;
        // Central directory offset field of the end record → 0xFFFFFFFF.
        const std::size_t eocd = z.size() - 22;
        for (int i = 0; i < 4; ++i) z[eocd + 16 + std::size_t(i)] = 0xFF;
        check(!zip::listEntries(z, entries, err) && err.find("zip64") != std::string::npos,
              "zip64 marker refused");
        z = good;
        z[eocd + 16] = 0xF0; z[eocd + 17] = 0xFF; z[eocd + 18] = 0xFF; z[eocd + 19] = 0x7F;
        check(!zip::listEntries(z, entries, err), "central directory outside the archive refused");
    }
    {
        // A bomb's directory: 40 members each declaring 4 GiB - 2. Nothing
        // is unpacked to learn that.
        std::vector<testzip::Member> ms;
        for (int i = 0; i < 40; ++i) {
            testzip::Member m{"m" + std::to_string(i), kFixed, 8, 0xFFFFFFFEu, 0};
            ms.push_back(m);
        }
        const auto z = testzip::make(ms);
        check(zip::listEntries(z, entries, err) &&
                  zip::totalUncompressed(entries) == 40ull * 0xFFFFFFFEull,
              "bomb gate: declared total read from the directory alone");
        check(!zip::readEntry(z, entries[0], out, err, 1 << 20) && out.empty(),
              "bomb member refused by the per-member cap");
    }

    std::printf("%s zip_reader_test (%d failure%s)\n", gFails ? "FAIL" : "PASS", gFails,
                gFails == 1 ? "" : "s");
    return gFails ? 1 : 0;
}
